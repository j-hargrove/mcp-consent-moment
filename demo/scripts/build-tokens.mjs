// Generates src/tokens.css from docs/design/tokens.json (DTCG). No dependencies.
// A token at color.role.ink becomes --color-role-ink; aliases become var() references.
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../../docs/design/tokens.json', import.meta.url);
const target = new URL('../src/tokens.css', import.meta.url);
const tokens = JSON.parse(readFileSync(source, 'utf8'));

const cssName = path => `--${path.join('-')}`;

function format(value, type) {
  switch (type) {
    case 'dimension':
    case 'duration':
      return `${value.value}${value.unit}`;
    case 'fontFamily':
      return value.map(f => (f.includes(' ') ? `'${f}'` : f)).join(', ');
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    default:
      return String(value);
  }
}

function lookup(path) {
  const node = path.split('.').reduce((n, key) => n?.[key], tokens);
  if (node?.$value === undefined) throw new Error(`Unresolved token alias: {${path}}`);
}

function walk(node, path, inheritedType, lines) {
  const type = node.$type ?? inheritedType;
  if (node.$value !== undefined) {
    const alias = typeof node.$value === 'string' && node.$value.match(/^\{(.+)\}$/);
    if (alias) lookup(alias[1]);
    const value = alias ? `var(${cssName(alias[1].split('.'))})` : format(node.$value, type);
    lines.push(`  ${cssName(path)}: ${value};`);
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (!key.startsWith('$')) walk(child, [...path, key], type, lines);
  }
}

const lines = [];
walk(tokens, [], undefined, lines);
writeFileSync(
  target,
  `/* Generated by scripts/build-tokens.mjs from docs/design/tokens.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`,
);
console.log(`tokens.css: ${lines.length} tokens`);
